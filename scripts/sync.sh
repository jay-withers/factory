#!/usr/bin/env bash
# Clone every non-archived repo under $FACTORY_OWNER into repos/<name>, and
# fast-forward the ones already there. A clone that is dirty or not on its
# default branch is reported and left alone - this never stashes, resets or
# switches branches, so it can't lose work. Also writes CATALOG.md (gitignored),
# which CLAUDE.md imports so Claude starts every session knowing the estate.
#
# Descriptions and topics come from GitHub, which Terraform in github-repos
# sets from terraform.tfvars, so this list can't drift from that one.
set -euo pipefail

owner="${FACTORY_OWNER:-jay-withers}"
root="$(cd "$(dirname "$0")/.." && pwd)"
repos_dir="$root/repos"
self="$(basename "$(git -C "$root" remote get-url origin)" .git)"

mkdir -p "$repos_dir"

json="$(gh repo list "$owner" --no-archived --limit 200 \
  --json name,description,repositoryTopics,defaultBranchRef,isTemplate)"

install_hooks() {
  local dir="$1"
  [[ -f "$dir/.pre-commit-config.yaml" ]] || return 0
  # Hooks live in the clone's .git, so every worktree made from it shares them.
  if [[ ! -f "$dir/.git/hooks/pre-commit" ]]; then
    (cd "$dir" && pre-commit install && pre-commit install --hook-type commit-msg) >/dev/null ||
      echo "  ! $(basename "$dir"): pre-commit install failed"
  fi
}

while IFS=$'\t' read -r name default; do
  [[ "$name" == "$self" ]] && continue
  dir="$repos_dir/$name"

  if [[ ! -d "$dir/.git" ]]; then
    echo "+ $name: cloning"
    gh repo clone "$owner/$name" "$dir" -- --quiet
    install_hooks "$dir"
    continue
  fi

  install_hooks "$dir"
  git -C "$dir" fetch --quiet --prune origin

  if [[ -n "$(git -C "$dir" status --porcelain)" ]]; then
    echo "! $name: uncommitted changes - skipped"
    continue
  fi
  branch="$(git -C "$dir" symbolic-ref --quiet --short HEAD || echo '(detached)')"
  if [[ "$branch" != "$default" ]]; then
    echo "! $name: on $branch, not $default - skipped"
    continue
  fi
  if ! git -C "$dir" merge --ff-only --quiet "origin/$default" 2>/dev/null; then
    echo "! $name: $default has diverged from origin - skipped"
  fi
done < <(jq -r '.[] | [.name, (.defaultBranchRef.name // "main")] | @tsv' <<<"$json")

# Clones of repos that have since been archived or deleted.
for dir in "$repos_dir"/*/; do
  [[ -d "$dir" ]] || continue
  name="$(basename "$dir")"
  if ! jq -e --arg n "$name" 'any(.[]; .name == $n)' <<<"$json" >/dev/null; then
    echo "? $name: no longer listed on GitHub (archived or deleted) - left in place"
  fi
done

{
  echo "# Repository catalogue"
  echo
  echo "Generated by \`make sync\` from \`gh repo list $owner\` - do not edit."
  echo "Each repo is cloned at \`repos/<name>\`. For grouping, apply order and"
  echo "dependencies, read \`repos/github-repos/terraform/terraform.tfvars\`."
  echo
  jq -r --arg self "$self" '
    sort_by(.name)[]
    | select(.name != $self)
    | "- **\(.name)**\(if .isTemplate then " (template)" else "" end)"
      + " - \(.description // "no description")"
      + (if (.repositoryTopics // []) | length > 0
         then " [" + ([.repositoryTopics[].name] | join(", ")) + "]"
         else "" end)
  ' <<<"$json"
} >"$root/CATALOG.md"

echo "Synced $(jq 'length' <<<"$json") repos; catalogue written to CATALOG.md"
